import plotext as plt
import math

# Генерируем тестовые данные (для примера)
y_water = [math.sin(i / 5) * 100 + 400 for i in range(50)] # Уровни воды от 300 до 500
y_temp = [math.cos(i / 5) * 5 + 15 for i in range(50)]     # Температура от 10 до 20

# 1. Полностью очищаем память библиотеки от прошлых запусков
plt.clf() 

# 2. Создаем сетку: 1 строка, 2 колонки
plt.subplots(1, 2)

# ==========================================
# НАСТРАИВАЕМ ПЕРВЫЙ ГРАФИК (Слева)
# ==========================================
plt.subplot(1, 1)  # Активируем левую ячейку

# Строим линию уровня воды (зеленая, плавная)
plt.plot(y_water, marker="braille", color="green")

# Добавляем горизонтальные линии (Пороги MHW / MNW)
plt.hline(480, color="red")    # Красная линия опасности
plt.hline(320, color="yellow") # Желтая линия межени

# Украшаем первый график
plt.title("Уровень воды (Lübeck-Bauhof)")
plt.canvas_color("none")
plt.axes_color("none")


# ==========================================
# НАСТРАИВАЕМ ВТОРОЙ ГРАФИК (Справа)
# ==========================================
plt.subplot(1, 2)  # Переключаем фокус на правую ячейку

# Строим график температуры (синий)
plt.plot(y_temp, marker="braille", color="cyan")

# Украшаем второй график
plt.title("Изменение температуры")
plt.canvas_color("none")
plt.axes_color("none")

# ==========================================
# ОБЩИЕ НАСТРОЙКИ И ВЫВОД
# ==========================================
# Задаем жесткий размер для всей композиции (например, 100 символов в ширину, 25 в высоту).
# Если закомментировать эту строку, график растянется на весь экран.
plt.plotsize(100, 25) 

# Рисуем всё, что накопили в памяти, в терминал
plt.show()